# ── 11. Dashboard Does Not Mutate Original Image ─────────────────────────────


def test_dashboard_does_not_mutate_original_image():
    """Test 11: Verify image processing does not alter original image bytes."""
    original_arr = np.random.randint(0, 256, (224, 224), dtype=np.uint8)
    sha_before = hashlib.sha256(original_arr.tobytes()).hexdigest()

    pil_img = Image.fromarray(original_arr)
    # Replicate dashboard image conversion
    arr_processed = np.array(pil_img.convert("L"))

    sha_after = hashlib.sha256(original_arr.tobytes()).hexdigest()
    assert sha_before == sha_after, "Original array data was mutated!"
    assert np.array_equal(original_arr, arr_processed)



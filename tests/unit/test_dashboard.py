def test_no_agent_logic_in_dashboard():
    """Test 3: Verify dashboard code does not duplicate agent calculations or decision logic."""
    dashboard_dir = _SRC / "cxr_reliability" / "dashboard"
    app_source = (dashboard_dir / "app.py").read_text(encoding="utf-8")
